-- Hand-added: an order settles under the model it was placed with, whatever happens to the shop.
CREATE FUNCTION reject_order_settlement_model_change() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.settlement_model_locked IS DISTINCT FROM OLD.settlement_model_locked THEN
    RAISE EXCEPTION 'orders.settlement_model_locked never changes (order %)', OLD.id
      USING ERRCODE = '23000';
  END IF;
  RETURN NEW;
END;
$$;
--> statement-breakpoint
CREATE TRIGGER orders_settlement_model_locked_immutable BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION reject_order_settlement_model_change();
