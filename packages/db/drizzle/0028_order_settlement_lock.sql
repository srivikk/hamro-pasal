-- Hand-added: existing orders take their shop's current model.
UPDATE orders SET settlement_model_locked = vendors.settlement_model
  FROM vendors
  WHERE vendors.id = orders.vendor_id
    AND orders.settlement_model_locked IS DISTINCT FROM vendors.settlement_model;
