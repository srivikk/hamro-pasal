import { z } from 'zod';

import { nepalPhoneSchema } from '../domain/entities';
import { fulfillmentModeSchema, paymentMethodSchema, payoutStatusSchema } from '../domain/enums';

/*
 * Financial reconciliation and payouts (Phase 22, SPEC §5). Balances are the double-entry ledger's:
 * "available" is the vendor's VENDOR_WALLET balance and "pending" its prepaid earnings still in
 * escrow. Served to vendors under /api/vendor/finance and to Super Admins under /api/admin/finance.
 */

/** The most one payout request may withdraw. */
export const MAX_PAYOUT_NPR = 1_000_000;
/** How many reconciled orders and payout requests GET /api/vendor/finance/ledger returns. */
export const VENDOR_FINANCE_RECENT_LIMIT = 20;
export const PAYOUT_BANK_REFERENCE_MAX_LENGTH = 100;
export const PAYOUT_REJECTION_REASON_MAX_LENGTH = 500;

/** Page sizes of GET /api/admin/finance/payouts. */
export const ADMIN_PAYOUT_DEFAULT_LIMIT = 50;
export const ADMIN_PAYOUT_MAX_LIMIT = 100;

/**
 * POST /api/vendor/finance/payout. `idempotency_key` is generated by the client per withdrawal:
 * resending it returns the same request, never a second hold.
 */
export const payoutRequestSchema = z.strictObject({
  idempotency_key: z.string().trim().min(8).max(100),
  amount_npr: z
    .number()
    .positive()
    .max(MAX_PAYOUT_NPR)
    .refine(
      (amount) => Math.abs(amount * 100 - Math.round(amount * 100)) < 1e-6,
      'amount_npr must be a whole number of paisa',
    ),
});
export type PayoutRequest = z.infer<typeof payoutRequestSchema>;

/** One payout request as its vendor sees it. */
export const payoutViewSchema = z.strictObject({
  id: z.uuid(),
  amount_npr: z.number().positive(),
  status: payoutStatusSchema,
  /** The bank transfer the Super Admin recorded; null unless APPROVED. */
  bank_reference: z.string().nullable(),
  /** Why it was rejected, when the Super Admin said; null otherwise. */
  rejection_reason: z.string().nullable(),
  requested_at: z.iso.datetime(),
  /** When it was approved or rejected; null while PENDING. */
  decided_at: z.iso.datetime().nullable(),
});
export type PayoutView = z.infer<typeof payoutViewSchema>;

/**
 * A DELIVERED order whose settlement the nightly reconciliation has verified. `vendor_cut_npr` is
 * what the order earned the shop: subtotal − commission, plus the delivery fee when the shop
 * delivered it. `wallet_amount_npr` is what the settlement journal posted to the wallet: the same
 * for a prepaid order, but only −commission for a COD order the shop delivered (it holds the cash).
 */
export const reconciledOrderSchema = z.strictObject({
  order_id: z.uuid(),
  payment_method: paymentMethodSchema,
  fulfillment: fulfillmentModeSchema,
  subtotal_npr: z.number(),
  delivery_fee_npr: z.number(),
  commission_npr: z.number(),
  vendor_cut_npr: z.number(),
  wallet_amount_npr: z.number(),
  delivered_at: z.iso.datetime(),
  reconciled_at: z.iso.datetime(),
});
export type ReconciledOrderView = z.infer<typeof reconciledOrderSchema>;

/** GET /api/vendor/finance/ledger. */
export const vendorFinanceLedgerResponseSchema = z.strictObject({
  vendor_id: z.uuid(),
  /** The VENDOR_WALLET balance: what can be withdrawn when positive, the dues when negative. */
  available_balance_npr: z.number(),
  /** Prepaid earnings still in escrow (paid, not delivered yet). */
  pending_balance_npr: z.number().nonnegative(),
  /** Already taken out of the available balance by requests that are still PENDING. */
  pending_payout_npr: z.number().nonnegative(),
  /** DELIVERED orders the nightly job has not reconciled yet. */
  unreconciled_order_count: z.number().int().nonnegative(),
  /** Newest reconciliation first. */
  reconciled_orders: z.array(reconciledOrderSchema),
  /** Newest request first. */
  payouts: z.array(payoutViewSchema),
});
export type VendorFinanceLedgerResponseBody = z.infer<typeof vendorFinanceLedgerResponseSchema>;

/**
 * POST /api/vendor/finance/payout: 201 for a new request, 200 (`replayed: true`) when the same
 * idempotency key is sent again.
 */
export const payoutRequestResponseSchema = z.strictObject({
  payout: payoutViewSchema,
  /** The wallet balance after the hold. */
  available_balance_npr: z.number(),
  replayed: z.boolean(),
});
export type PayoutRequestResponseBody = z.infer<typeof payoutRequestResponseSchema>;

/** GET /api/admin/finance/payouts?status=&limit=&cursor=: newest request first. */
export const adminPayoutListQuerySchema = z.strictObject({
  status: payoutStatusSchema.optional(),
  limit: z
    .string()
    .trim()
    .regex(/^\d{1,3}$/, 'limit must be a whole number')
    .transform(Number)
    .pipe(z.number().int().min(1).max(ADMIN_PAYOUT_MAX_LIMIT))
    .optional(),
  cursor: z.uuid().optional(),
});
export type AdminPayoutListQuery = z.output<typeof adminPayoutListQuerySchema>;

/** A payout request as the Super Admin sees it. */
export const adminPayoutViewSchema = payoutViewSchema.extend({
  vendor: z.strictObject({
    id: z.uuid(),
    business_name: z.string().min(1),
    phone: nepalPhoneSchema,
    /** The vendor's wallet now (the requested amount has already left it). */
    wallet_balance_npr: z.number(),
  }),
  decided_by: z.uuid().nullable(),
});
export type AdminPayoutView = z.infer<typeof adminPayoutViewSchema>;

export const adminPayoutListResponseSchema = z.strictObject({
  payouts: z.array(adminPayoutViewSchema),
  next_cursor: z.uuid().nullable(),
});
export type AdminPayoutListResponseBody = z.infer<typeof adminPayoutListResponseSchema>;

/** POST /api/admin/finance/payouts/:id/approve: the reference of the bank transfer that paid it. */
export const adminPayoutApproveRequestSchema = z.strictObject({
  bank_reference: z.string().trim().min(1).max(PAYOUT_BANK_REFERENCE_MAX_LENGTH),
});
export type AdminPayoutApproveRequest = z.infer<typeof adminPayoutApproveRequestSchema>;

/** POST /api/admin/finance/payouts/:id/reject. A blank reason is stored as none. */
export const adminPayoutRejectRequestSchema = z.strictObject({
  reason: z
    .string()
    .trim()
    .max(PAYOUT_REJECTION_REASON_MAX_LENGTH)
    .transform((reason) => (reason === '' ? null : reason))
    .nullable()
    .default(null),
});
export type AdminPayoutRejectRequest = z.infer<typeof adminPayoutRejectRequestSchema>;

/** Approve and reject answer with the request after the decision (200, also on a repeat). */
export const adminPayoutDecisionResponseSchema = z.strictObject({
  payout: adminPayoutViewSchema,
});
export type AdminPayoutDecisionResponseBody = z.infer<typeof adminPayoutDecisionResponseSchema>;
