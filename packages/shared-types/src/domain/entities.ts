import { z } from 'zod';

import {
  NEPAL_PHONE_REGEX,
  NEPAL_PROVINCE_ID_MAX,
  NEPAL_PROVINCE_ID_MIN,
  VENDOR_WALLET_HARD_FLOOR_NPR,
} from './constants';
import {
  deliveryScopeSchema,
  disputeStatusSchema,
  fulfillmentModeSchema,
  ledgerAccountTypeSchema,
  ledgerTransactionKindSchema,
  orderStateSchema,
  paymentMethodSchema,
  paymentStatusSchema,
  pricingModelSchema,
  reviewDirectionSchema,
  userRoleSchema,
  vendorFulfillmentModeSchema,
  vendorStatusSchema,
} from './enums';
import { MAX_CHAT_ATTACHMENTS, MAX_CHAT_MESSAGE_LENGTH } from '../realtime/chat-socket';

/*
 * Persisted row shapes. Field names mirror the Postgres columns (snake_case, as in SPEC.md).
 * packages/db asserts at compile time that every Drizzle table's select type equals the
 * matching type below, and at runtime that real rows parse with these schemas.
 */

export const nepalPhoneSchema = z.string().regex(NEPAL_PHONE_REGEX, 'Must be a +977 mobile number');
/** Amount in NPR (2 decimal places in the database). */
export const nprAmountSchema = z.number();
const nonNegativeNprSchema = nprAmountSchema.nonnegative();
const nonEmptyTextSchema = z.string().trim().min(1);

/** PostGIS Point(SRID 4326). `x` is longitude, `y` is latitude. */
export const geoPointSchema = z.object({
  x: z.number().min(-180).max(180),
  y: z.number().min(-90).max(90),
});
export type GeoPoint = z.infer<typeof geoPointSchema>;

export const userSchema = z.strictObject({
  id: z.uuid(),
  phone: nepalPhoneSchema,
  role: userRoleSchema,
  /** Null for customers who signed up by OTP and have not added a name yet. */
  first_name: nonEmptyTextSchema.nullable(),
  last_name: nonEmptyTextSchema.nullable(),
  created_at: z.date(),
  updated_at: z.date(),
});
export type User = z.infer<typeof userSchema>;

/** Nepal address hierarchy (SPEC: Nepal localizations §3). Western ZIP codes are not modelled. */
export const customerAddressSchema = z.strictObject({
  id: z.uuid(),
  user_id: z.uuid(),
  province_id: z.number().int().min(NEPAL_PROVINCE_ID_MIN).max(NEPAL_PROVINCE_ID_MAX),
  district_string: nonEmptyTextSchema,
  municipality_palika_string: nonEmptyTextSchema,
  ward_number: z.number().int().positive(),
  tole_locality: nonEmptyTextSchema,
  landmark: nonEmptyTextSchema,
  exact_lat: z.number().min(-90).max(90),
  exact_lng: z.number().min(-180).max(180),
  /** Generated by the database from exact_lng/exact_lat. */
  location: geoPointSchema,
  created_at: z.date(),
  updated_at: z.date(),
});
export type CustomerAddress = z.infer<typeof customerAddressSchema>;

export const vendorSchema = z.strictObject({
  id: z.uuid(),
  user_id: z.uuid(),
  business_name: nonEmptyTextSchema,
  phone: nepalPhoneSchema,
  status: vendorStatusSchema,
  /** Null until the vendor picks a model; required once LIVE (SPEC vendor flow step 5). */
  pricing_model: pricingModelSchema.nullable(),
  lock_in_expiry: z.date().nullable(),
  scheduled_downgrade: z.boolean(),
  /** Fraction, e.g. 0.1 = 10%. Always 0 on SUBSCRIPTION. */
  commission_rate: z.number().min(0).max(1),
  delivery_scope: deliveryScopeSchema,
  /** Copied onto each order as fulfillment_locked at checkout. */
  fulfillment_mode: vendorFulfillmentModeSchema,
  radius_km: z.number().positive(),
  /**
   * Same field as CustomerAddress.municipality_palika_string. CITY_WIDE vendors serve customers
   * whose address carries the same Palika (SPEC §2).
   */
  municipality_palika_string: nonEmptyTextSchema,
  min_order_value: nonNegativeNprSchema,
  base_delivery_fee_npr: nonNegativeNprSchema,
  location: geoPointSchema,
  /** Below the hard floor only while SUSPENDED. */
  wallet_balance_npr: nprAmountSchema,
  /**
   * Set only while the vendor is SUSPENDED for wallet debt (SPEC §5): the status to restore once the
   * negative balance is cleared. Null for any other suspension, which a top-up never lifts.
   */
  status_before_debt_suspension: vendorStatusSchema.exclude(['SUSPENDED']).nullable(),
  created_at: z.date(),
  updated_at: z.date(),
});
export type Vendor = z.infer<typeof vendorSchema>;

export const productSchema = z.strictObject({
  id: z.uuid(),
  vendor_id: z.uuid(),
  name: nonEmptyTextSchema,
  price_npr: nprAmountSchema.positive(),
  stock_quantity: z.number().int().nonnegative(),
  is_active: z.boolean(),
  created_at: z.date(),
  updated_at: z.date(),
});
export type Product = z.infer<typeof productSchema>;

/** SPEC `OrderSnapshot`, plus idempotency and gateway reference columns. */
export const orderSchema = z.strictObject({
  id: z.uuid(),
  /** Client-generated per checkout attempt; unique, so retried submissions cannot duplicate. */
  idempotency_key: nonEmptyTextSchema,
  customer_id: z.uuid(),
  vendor_id: z.uuid(),
  /** The 600 s Redis inventory lock created at checkout and claimed when payment confirms. */
  reservation_id: z.uuid().nullable(),
  /** Platform-fleet rider. Required before a PLATFORM_FLEET / EMERGENCY_FLEET order is DELIVERED. */
  driver_user_id: z.uuid().nullable(),
  state: orderStateSchema,
  subtotal: nonNegativeNprSchema,
  delivery_fee: nonNegativeNprSchema,
  platform_commission_amount: nonNegativeNprSchema,
  fulfillment_locked: fulfillmentModeSchema,
  payment_method: paymentMethodSchema,
  payment_status: paymentStatusSchema,
  /** eSewa transaction_uuid or Khalti pidx. Unique per gateway, and always null for COD. */
  payment_gateway_ref: nonEmptyTextSchema.nullable(),
  /**
   * bcrypt hash of the 4-digit handoff OTP. The raw OTP is never stored. Cleared (null) when the
   * order is DELIVERED, so a used code can never be replayed.
   */
  delivery_otp: z
    .string()
    .regex(/^\$2[aby]\$/, 'Must be a bcrypt hash')
    .nullable(),
  /** Set when the order becomes PLACED; anchors the 60 s cancellation window. */
  placed_at: z.date().nullable(),
  delivered_at: z.date().nullable(),
  /** A PAID order was canceled; its escrowed payment must go back to the customer's gateway. */
  refund_required: z.boolean(),
  created_at: z.date(),
  updated_at: z.date(),
});
export type Order = z.infer<typeof orderSchema>;
/** Alias matching the SPEC.md interface name. */
export type OrderSnapshot = Order;

/**
 * The delivery address captured at checkout, copied from the customer's input so later address
 * edits never rewrite where an order was delivered. Same Nepal hierarchy as CustomerAddress.
 */
export const orderAddressSchema = z.strictObject({
  order_id: z.uuid(),
  province_id: z.number().int().min(NEPAL_PROVINCE_ID_MIN).max(NEPAL_PROVINCE_ID_MAX),
  district_string: nonEmptyTextSchema,
  municipality_palika_string: nonEmptyTextSchema,
  ward_number: z.number().int().positive(),
  tole_locality: nonEmptyTextSchema,
  landmark: nonEmptyTextSchema,
  exact_lat: z.number().min(-90).max(90),
  exact_lng: z.number().min(-180).max(180),
  /** Generated by the database from exact_lng/exact_lat. */
  location: geoPointSchema,
  created_at: z.date(),
});
export type OrderAddress = z.infer<typeof orderAddressSchema>;

export const orderItemSchema = z.strictObject({
  id: z.uuid(),
  order_id: z.uuid(),
  product_id: z.uuid(),
  /** Snapshot at purchase time: later catalog edits do not rewrite history. */
  product_name: nonEmptyTextSchema,
  unit_price_npr: nprAmountSchema.positive(),
  quantity: z.number().int().positive(),
  created_at: z.date(),
});
export type OrderItem = z.infer<typeof orderItemSchema>;

/*
 * Double-entry ledger. Money moves between accounts; every journal transaction's postings sum
 * to exactly zero (enforced by a deferred DB constraint trigger). A posting's amount is the
 * signed change to its account's balance. VENDOR_WALLET balances are mirrored into
 * vendors.wallet_balance_npr, which drives the SPEC §5 suspension rules.
 */

export const ledgerAccountSchema = z.strictObject({
  id: z.uuid(),
  account_type: ledgerAccountTypeSchema,
  /** Owner of a VENDOR_WALLET account, otherwise null. */
  vendor_id: z.uuid().nullable(),
  /** Owner of a DRIVER_WALLET account, otherwise null. */
  driver_user_id: z.uuid().nullable(),
  /** Gateway of a GATEWAY_CLEARING account (ESEWA / KHALTI), otherwise null. */
  gateway: paymentMethodSchema.nullable(),
  balance_npr: nprAmountSchema,
  created_at: z.date(),
  updated_at: z.date(),
});
export type LedgerAccount = z.infer<typeof ledgerAccountSchema>;

export const ledgerTransactionSchema = z.strictObject({
  id: z.uuid(),
  kind: ledgerTransactionKindSchema,
  /** Deterministic per business event (e.g. `settlement:<order_id>`), so replays are no-ops. */
  idempotency_key: nonEmptyTextSchema,
  order_id: z.uuid().nullable(),
  description: nonEmptyTextSchema.nullable(),
  created_at: z.date(),
});
export type LedgerTransaction = z.infer<typeof ledgerTransactionSchema>;

export const ledgerEntrySchema = z.strictObject({
  id: z.uuid(),
  transaction_id: z.uuid(),
  account_id: z.uuid(),
  /** Signed change to the account balance; never zero. */
  amount_npr: nprAmountSchema.refine((value) => value !== 0, 'Must be non-zero'),
  created_at: z.date(),
});
export type LedgerEntry = z.infer<typeof ledgerEntrySchema>;

export const disputeSchema = z.strictObject({
  id: z.uuid(),
  order_id: z.uuid(),
  opened_by_user_id: z.uuid(),
  reason: nonEmptyTextSchema,
  status: disputeStatusSchema,
  resolved_by_user_id: z.uuid().nullable(),
  resolved_at: z.date().nullable(),
  created_at: z.date(),
  updated_at: z.date(),
});
export type Dispute = z.infer<typeof disputeSchema>;

/** An image attached to a dispute chat message, as stored (a chat attachment). */
export const storedChatAttachmentSchema = z.strictObject({
  url: z.url({ protocol: /^https?$/ }),
  content_type: z.string().regex(/^image\/[a-z0-9.+-]+$/),
});
export type StoredChatAttachment = z.infer<typeof storedChatAttachmentSchema>;

/**
 * One persisted dispute chat message (the transcript Super Admin arbitrates from). The sender is a
 * reference only: names are joined in, and privacy-filtered, when a message is broadcast.
 */
export const chatMessageRowSchema = z.strictObject({
  id: z.uuid(),
  dispute_id: z.uuid(),
  sender_user_id: z.uuid(),
  /** The sending device's id for the message; unique per sender and dispute (retries dedupe). */
  client_id: z.string().min(1).max(100),
  body: z.string().max(MAX_CHAT_MESSAGE_LENGTH),
  attachments: z.array(storedChatAttachmentSchema).max(MAX_CHAT_ATTACHMENTS),
  created_at: z.date(),
});
export type ChatMessageRow = z.infer<typeof chatMessageRowSchema>;

/** Double-blind: quarantined (`is_published = false`) until both sides submit or 48h elapse. */
export const reviewSchema = z.strictObject({
  id: z.uuid(),
  order_id: z.uuid(),
  direction: reviewDirectionSchema,
  rating: z.number().int().min(1).max(5),
  comment: nonEmptyTextSchema.nullable(),
  is_published: z.boolean(),
  published_at: z.date().nullable(),
  created_at: z.date(),
});
export type Review = z.infer<typeof reviewSchema>;

/** Single-row platform configuration managed by Super Admin. */
export const platformSettingsSchema = z.strictObject({
  id: z.literal(true),
  /** Suspension triggers when a wallet drops strictly below this. Range: [-2000, 0]. */
  vendor_wallet_suspension_limit_npr: nprAmountSchema.min(VENDOR_WALLET_HARD_FLOOR_NPR).max(0),
  updated_at: z.date(),
});
export type PlatformSettings = z.infer<typeof platformSettingsSchema>;
